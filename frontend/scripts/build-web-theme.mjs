/**
 * Generates lms/public/css/jutsu-web.css — the Jutsu theme for Frappe's own
 * server-rendered pages (login, sign-up, forgot-password, the website shell).
 *
 * Those pages are NOT the SPA. They are rendered by Frappe's website bundle
 * with its own stylesheet, so nothing the app imports reaches them — which is
 * why /login stayed light while the whole app went dark. They do, however, use
 * the same espresso token names the SPA does (`--ink-gray-9`, `--surface-base`,
 * `.es-button`, `.page-card`), so re-declaring those variables is enough to
 * carry the theme across.
 *
 * DERIVED, never hand-edited: the token values are read out of
 * src/styles/jutsuTokens.css and the @font-face rules out of the freshly built
 * bundle (the Geist filenames are content-hashed, so hardcoding them would
 * break on the next build). Run after `vite build` — `yarn build` chains it.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const frontend = resolve(here, '..')
const app = resolve(frontend, '..', 'lms')
const builtAssets = join(app, 'public', 'frontend', 'assets')
const out = join(app, 'public', 'css', 'jutsu-web.css')

/** Pull one selector's declaration block out of a stylesheet. */
function block(css, selector) {
	const start = css.indexOf(selector)
	if (start === -1) throw new Error(`${selector} not found in jutsuTokens.css`)
	const open = css.indexOf('{', start)
	const close = css.indexOf('\n}', open)
	if (open === -1 || close === -1) throw new Error(`unterminated ${selector}`)
	return css.slice(open + 1, close)
}

const tokens = readFileSync(join(frontend, 'src/styles/jutsuTokens.css'), 'utf8')

// Frappe's website pages have no theme switcher and no `data-theme` on <html>,
// and the login page already uses `data-theme` for something else entirely
// (`data-theme="red"` on its alert). So the dark values go on bare `:root`
// rather than behind an attribute selector: these pages are dark, full stop,
// which is also the app's default.
const light = block(tokens, ':root {')
const dark = block(tokens, "[data-theme='dark'] {")

// The built bundle's Geist faces, taken verbatim so the hashed URLs stay valid.
const bundle = readdirSync(builtAssets).find(
	(f) => f.startsWith('index-') && f.endsWith('.css')
)
if (!bundle) throw new Error('no built index-*.css; run vite build first')
const bundleCss = readFileSync(join(builtAssets, bundle), 'utf8')
const faces = bundleCss.match(
	/@font-face\{font-family:Geist Variable[^}]*\}/g
)
if (!faces?.length) throw new Error('no Geist @font-face rules in the bundle')

const css = `/* GENERATED by frontend/scripts/build-web-theme.mjs — do not edit.
 * Source of truth: frontend/src/styles/jutsuTokens.css
 * Regenerate with: yarn build (in frontend/)
 *
 * The Jutsu theme for Frappe's server-rendered pages — login, sign-up,
 * forgot-password. Wired up by \`web_include_css\` in lms/hooks.py.
 */

${faces.join('\n')}

/* \`:root:root\`, not \`:root\`.
 *
 * Frappe's own login.bundle.css loads AFTER this file and redefines the very
 * same espresso variables on a plain \`:root\` — \`--surface-base: #ffffff\`,
 * \`--ink-gray-9: #0f0f0f\`. At equal specificity the later sheet wins, so the
 * page came out light with only the tokens Frappe does not define (the canvas,
 * the grid) surviving. Repeating the selector raises specificity to (0,2,0),
 * which outranks it without reaching for \`!important\` — and leaves
 * \`!important\` available further down for the handful of properties Frappe
 * paints directly on elements rather than through a variable.
 *
 * Light values first so every token has a definition, then the dark ones over
 * the top: these pages are always dark. Both blocks are lifted verbatim from
 * the app's token file. */
:root:root {
${light}
}

:root:root {
${dark}
}

:root:root {
	color-scheme: dark;
}

html body,
html {
	background-color: var(--surface-canvas);
	background-image: linear-gradient(
			to right,
			var(--grid-line) 1px,
			transparent 1px
		),
		linear-gradient(to bottom, var(--grid-line) 1px, transparent 1px);
	background-size: var(--grid-size) var(--grid-size);
	color: var(--ink-gray-9);
	font-family: 'Geist Variable', ui-sans-serif, system-ui, -apple-system,
		'Segoe UI', sans-serif;
	-webkit-font-smoothing: antialiased;
	-moz-osx-font-smoothing: grayscale;
}

/* The sign-in card. Frappe centres \`.page-card\` on the page; the Jutsu
   treatment is the app's floating surface — a lifted card with a hairline
   border, not a shadowed white sheet. */
.page-card {
	/* Frappe's own rule paints this white on the element itself, so the token
	   override above cannot reach it — this is one of the few places the
	   important flag is the honest tool rather than a shortcut. */
	background-color: var(--surface-base) !important;
	border: 1px solid var(--outline-gray-2);
	border-radius: 14px;
	box-shadow: var(--elevation-lg);
	color: var(--ink-gray-9);
}

.page-card-head-text h4,
.page-card h4 {
	color: var(--ink-gray-9);
	letter-spacing: -0.02em;
}

.page-card-subtitle,
.text-ink-gray-6 {
	color: var(--ink-gray-5);
}

/* The product mark sits on the translucent light plate the app uses for logos,
   so a dark-on-transparent logo stays legible on a dark card. */
.page-card .app-logo {
	background-color: var(--logo-plate);
	border-radius: 8px;
	padding: 4px;
	box-sizing: content-box;
}

/* Inputs: the app's field geometry — 10px radius, card fill, brand focus. */
.form-control,
.form-control:not(:focus),
input[type='text'],
input[type='email'],
input[type='password'],
input[type='number'],
select,
textarea {
	background-color: var(--surface-gray-1);
	border: 1px solid var(--outline-gray-2);
	border-radius: 10px;
	color: var(--ink-gray-9);
}

.form-control::placeholder,
input::placeholder {
	color: var(--ink-gray-4);
}

.form-control:focus,
input:focus,
select:focus,
textarea:focus {
	background-color: var(--surface-gray-1);
	border-color: var(--outline-blue-5);
	color: var(--ink-gray-9);
	outline: var(--focus-outline-blue);
	outline-offset: 0;
	box-shadow: none;
}

/* Frappe's espresso button, given the app's primary. \`data-variant="solid"\`
   is the submit action; everything else reads as the subtle variant. */
.es-button[data-variant='solid'] {
	background-color: var(--surface-blue-6);
	border-color: transparent;
	border-radius: 10px;
	color: var(--ink-base);
}

.es-button[data-variant='solid']:hover {
	background-color: var(--surface-blue-7);
}

.es-button:not([data-variant='solid']) {
	background-color: var(--surface-gray-2);
	border: 1px solid var(--outline-gray-2);
	border-radius: 10px;
	color: var(--ink-gray-8);
}

.es-button:not([data-variant='solid']):hover {
	background-color: var(--surface-gray-3);
}

a {
	color: var(--ink-blue-link);
}

a.text-ink-gray-5,
a.text-ink-gray-6 {
	color: var(--ink-gray-5);
}

a:hover {
	color: var(--ink-blue-6);
}

/* Frappe paints its own light greys on these; without an override they stay
   white cards on the dark canvas. */
.card,
.web-card,
.page-content-wrapper .page_content > .card {
	background-color: var(--surface-base);
	border-color: var(--outline-gray-2);
	color: var(--ink-gray-9);
}

hr,
.divider {
	border-color: var(--outline-gray-2);
}

::selection {
	background: color-mix(in oklab, var(--brand) 28%, transparent);
	color: var(--ink-gray-9);
}
`

writeFileSync(out, css)
console.log(
	`build-web-theme: wrote ${out} (${faces.length} font faces, ${css.length} bytes)`
)
